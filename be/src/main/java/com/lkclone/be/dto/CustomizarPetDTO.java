package com.lkclone.be.dto;

public class CustomizarPetDTO {

    private String cor;
    private String chapeu;
    private String rosto;
    private String acessorioCorpo;

    public String getCor() {
        return cor;
    }

    public void setCor(String cor) {
        this.cor = cor;
    }

    public String getChapeu() {
        return chapeu;
    }

    public void setChapeu(String chapeu) {
        this.chapeu = chapeu;
    }

    public String getRosto() {
        return rosto;
    }

    public void setRosto(String rosto) {
        this.rosto = rosto;
    }

    public String getAcessorioCorpo() {
        return acessorioCorpo;
    }

    public void setAcessorioCorpo(String acessorioCorpo) {
        this.acessorioCorpo = acessorioCorpo;
    }
}
